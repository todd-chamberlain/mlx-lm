"""
Pydantic models for OpenAI-compatible API endpoints.
"""

import time
import uuid
from typing import List, Optional, Dict, Any, Union, Literal
from pydantic import BaseModel, Field, validator


class ChatMessage(BaseModel):
    """A chat message."""
    role: Literal["system", "user", "assistant"] = Field(..., description="The role of the message author")
    content: str = Field(..., description="The content of the message")
    name: Optional[str] = Field(None, description="The name of the author")


class ChatCompletionRequest(BaseModel):
    """Request model for chat completions."""
    model: str = Field(..., description="ID of the model to use")
    messages: List[ChatMessage] = Field(..., description="List of messages comprising the conversation")
    temperature: Optional[float] = Field(1.0, ge=0.0, le=2.0, description="Sampling temperature")
    top_p: Optional[float] = Field(1.0, ge=0.0, le=1.0, description="Nucleus sampling parameter")
    max_tokens: Optional[int] = Field(None, ge=1, description="Maximum number of tokens to generate")
    stream: Optional[bool] = Field(False, description="Whether to stream partial message deltas")
    seed: Optional[int] = Field(None, description="Random seed for deterministic generation")
    stop: Optional[Union[str, List[str]]] = Field(None, description="Stop sequences")
    presence_penalty: Optional[float] = Field(0.0, ge=-2.0, le=2.0, description="Presence penalty")
    frequency_penalty: Optional[float] = Field(0.0, ge=-2.0, le=2.0, description="Frequency penalty")
    user: Optional[str] = Field(None, description="Unique identifier for the end-user")
    
    # Internal fields
    id: Optional[str] = Field(default_factory=lambda: str(uuid.uuid4()), description="Request ID")
    
    @validator('messages')
    def validate_messages(cls, v):
        """Validate that messages list is not empty."""
        if not v:
            raise ValueError("Messages list cannot be empty")
        return v
    
    def to_prompt(self) -> str:
        """Convert messages to a single prompt string."""
        prompt_parts = []
        for message in self.messages:
            if message.role == "system":
                prompt_parts.append(f"System: {message.content}")
            elif message.role == "user":
                prompt_parts.append(f"User: {message.content}")
            elif message.role == "assistant":
                prompt_parts.append(f"Assistant: {message.content}")
        
        prompt_parts.append("Assistant:")
        return "\n".join(prompt_parts)


class ChatCompletionChoice(BaseModel):
    """A choice in a chat completion response."""
    index: int = Field(..., description="The index of the choice")
    message: ChatMessage = Field(..., description="The message generated by the model")
    finish_reason: Optional[Literal["stop", "length", "content_filter", "tool_calls"]] = Field(
        None, description="The reason the model stopped generating tokens"
    )


class ChatCompletionUsage(BaseModel):
    """Usage statistics for a chat completion."""
    prompt_tokens: int = Field(..., description="Number of tokens in the prompt")
    completion_tokens: int = Field(..., description="Number of tokens in the completion")
    total_tokens: int = Field(..., description="Total number of tokens used")


class ChatCompletionResponse(BaseModel):
    """Response model for chat completions."""
    id: str = Field(..., description="Unique identifier for the chat completion")
    object: Literal["chat.completion"] = Field("chat.completion", description="Object type")
    created: int = Field(default_factory=lambda: int(time.time()), description="Unix timestamp")
    model: str = Field(..., description="The model used for the chat completion")
    choices: List[ChatCompletionChoice] = Field(..., description="List of completion choices")
    usage: ChatCompletionUsage = Field(..., description="Usage statistics")
    system_fingerprint: Optional[str] = Field(None, description="System fingerprint")


class ChatCompletionStreamChoice(BaseModel):
    """A choice in a streaming chat completion response."""
    index: int = Field(..., description="The index of the choice")
    delta: Dict[str, Any] = Field(..., description="The delta message")
    finish_reason: Optional[Literal["stop", "length", "content_filter", "tool_calls"]] = Field(
        None, description="The reason the model stopped generating tokens"
    )


class ChatCompletionStreamResponse(BaseModel):
    """Response model for streaming chat completions."""
    id: str = Field(..., description="Unique identifier for the chat completion")
    object: Literal["chat.completion.chunk"] = Field("chat.completion.chunk", description="Object type")
    created: int = Field(default_factory=lambda: int(time.time()), description="Unix timestamp")
    model: str = Field(..., description="The model used for the chat completion")
    choices: List[ChatCompletionStreamChoice] = Field(..., description="List of completion choices")
    error: Optional[str] = Field(None, description="Error message if any")


class ModelInfo(BaseModel):
    """Information about a model."""
    id: str = Field(..., description="Model identifier")
    object: Literal["model"] = Field("model", description="Object type")
    created: int = Field(..., description="Unix timestamp when the model was created")
    owned_by: str = Field(..., description="Organization that owns the model")


class ModelsResponse(BaseModel):
    """Response model for listing models."""
    object: Literal["list"] = Field("list", description="Object type")
    data: List[ModelInfo] = Field(..., description="List of model objects")


class ShardedModelHealth(BaseModel):
    """Health information for a sharded model."""
    model_name: str = Field(..., description="Model name")
    total_shards: int = Field(..., description="Total number of shards")
    healthy_shards: int = Field(..., description="Number of healthy shards")
    status: Literal["ready", "degraded", "offline"] = Field(..., description="Model status")


